#!/usr/bin/env bash
# Bring up (or tear down) the isolated demo stand used to capture the
# documentation screenshots.
#
#   scripts/demo-stand.sh up      # build, start, wait, seed
#   scripts/demo-stand.sh down    # stop and delete the stand's data
#   scripts/demo-stand.sh seed    # re-seed a stand that is already up
#   scripts/demo-stand.sh status
#
# The stand is a second, independent copy of the whole stack. It exists
# because the live instance holds real engagement data — hosts, credentials,
# findings — and a screenshot of it would publish that data. Everything here
# is namespaced away from the live stack: its own compose project, its own
# container names, its own database volume, its own /data directory, its own
# secrets, and its own port. The live stack is never stopped, rebuilt or read.
#
# Secrets are generated on first `up` into .env.demo, which is gitignored.
# They are deliberately NOT the live secrets: this instance is throwaway and
# its database is meant to be deleted.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

# The CE tree is a copy of this one and carries this script, so a CE stand is
# raised by running it from there — with its own project name and port, or it
# would collide with the EE stand on container names and on 8899.
PROJECT="${DEMO_PROJECT:-umbryx-demo}"
PREFIX="${DEMO_PREFIX:-${PROJECT//-/_}}"
ENV_FILE="$REPO/.env.demo"
# Inside the repo, not /tmp: /tmp is world-writable, so on a shared host
# another user could create the data directory — or the file standing in for
# the docker socket — before the stand does, and the socket placeholder is
# precisely what keeps the stand away from the host daemon.
DATA_DIR="${DEMO_DATA_DIR:-$REPO/.demo-data}"
PORT="${DEMO_PORT:-8899}"
COMPOSE=(docker compose -p "$PROJECT" --env-file "$ENV_FILE"
         -f docker-compose.yml -f docker-compose.demo.yml)

die() { echo "error: $*" >&2; exit 1; }

refuse_if_live_ports() {
  # 8888 is the live stack, 3000 and 8000 are taken by other projects on this
  # host. Starting on one of those would either fail or, worse, shadow a
  # running service.
  case "$PORT" in
    8888) die "DEMO_PORT=8888 is the live instance — pick another port" ;;
  esac
  if ss -ltn "sport = :$PORT" 2>/dev/null | grep -q LISTEN; then
    die "port $PORT is already in use — set DEMO_PORT to a free one"
  fi
}

gen_env() {
  [ -f "$ENV_FILE" ] && return 0
  echo "==> generating $ENV_FILE (throwaway secrets, not the live ones)"
  local pw jwt enc rpw
  pw="$(openssl rand -hex 16)"
  jwt="$(openssl rand -hex 32)"
  enc="$(openssl rand -base64 32)"
  rpw="$(openssl rand -hex 16)"
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/demo-stand.sh for the throwaway screenshot stand.
# Not the live instance's secrets, and not meant to be kept.
DB_USER=umbryx
DB_PASSWORD=$pw
DB_NAME=umbryx
POSTGRES_USER=umbryx
POSTGRES_PASSWORD=$pw
POSTGRES_DB=umbryx
REDIS_PASSWORD=$rpw
JWT_SECRET=$jwt
ENCRYPTION_KEY=$enc
ADMIN_USERNAME=admin
ADMIN_PASSWORD=DemoStand2026!
PORT=$PORT
COOKIE_SECURE=false
# Own image tags. docker-compose.yml both builds and tags, so without these
# the stand's build would overwrite the live stack's umbryx-backend:latest
# and umbryx-frontend:latest.
BACKEND_IMAGE=$PROJECT-backend
FRONTEND_IMAGE=$PROJECT-frontend
CORS_ORIGINS=
DEMO_DATA_DIR=$DATA_DIR
DEMO_DOCKER_SOCKET=$DATA_DIR/no-docker.sock
DEMO_SUBNET=${DEMO_SUBNET:-10.201.0.0/24}
DEMO_PREFIX=$PREFIX
EOF
  chmod 600 "$ENV_FILE"
}

prepare_data_dir() {
  [ "$DATA_DIR" = "$REPO/data" ] && die "DEMO_DATA_DIR must not be the live ./data"
  [ -L "$DATA_DIR" ] && die "$DATA_DIR is a symlink — refusing to use it"
  mkdir -p "$DATA_DIR"
  chmod 700 "$DATA_DIR"
  [ -L "$DATA_DIR/no-docker.sock" ] && die "$DATA_DIR/no-docker.sock is a symlink — refusing"
  # The base compose file mounts the docker socket unconditionally. Point it
  # at an empty regular file so the stand cannot reach the host daemon; a
  # nonexistent path would make docker create a directory instead.
  : > "$DATA_DIR/no-docker.sock"
}

wait_healthy() {
  echo "==> waiting for the stand to answer on :$PORT"
  for _ in $(seq 1 90); do
    if curl -fsS "http://localhost:$PORT/api/health" >/dev/null 2>&1; then
      echo "    up"
      return 0
    fi
    sleep 2
  done
  die "the stand did not become healthy — check: ${COMPOSE[*]} logs backend"
}

seed() {
  echo "==> seeding synthetic data"
  "${COMPOSE[@]}" exec -T backend python /app/scripts/seed_demo.py
}

case "${1:-}" in
  up)
    refuse_if_live_ports
    gen_env
    prepare_data_dir
    echo "==> building (live stack untouched)"
    "${COMPOSE[@]}" build backend frontend
    "${COMPOSE[@]}" up -d
    wait_healthy
    seed
    echo
    # The seeder rewrites every password hash, including admin's, so the
    # credential to use is the seeder's, not ADMIN_PASSWORD from .env.demo.
    echo "demo stand: http://localhost:$PORT  (admin / Demo2024!)"
    ;;
  seed)
    seed
    ;;
  down)
    echo "==> stopping the stand and deleting its database"
    "${COMPOSE[@]}" down -v
    rm -rf "$DATA_DIR"
    echo "    gone ($ENV_FILE kept)"
    ;;
  status)
    "${COMPOSE[@]}" ps
    ;;
  *)
    sed -n '2,17p' "${BASH_SOURCE[0]}" | sed 's/^# \?//'
    exit 1
    ;;
esac
